import { compile } from 'sass';
import postcss from 'postcss';
import { writeFileSync } from 'node:fs';

// Compile selected Bootstrap components, then scope their selectors as CSS Modules.
const result = compile('components/admin/Bootstrap.module.scss', {
  loadPaths: ['node_modules'],
  quietDeps: true,
  silenceDeprecations: ['import', 'global-builtin', 'color-functions'],
  style: 'expanded',
});
const sheet = postcss.parse(result.css);
sheet.walkRules((rule) => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map((selector) => {
    const rest = selector.replace('.root', '').trim();
    return rest ? `.root :global(${rest})` : '.root';
  });
});
writeFileSync(
  'components/admin/Bootstrap.module.css',
  '/* Generated by npm run build:admin-css. */\n' + sheet.toString(),
);
