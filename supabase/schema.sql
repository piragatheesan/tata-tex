-- Reset identity counters after an explicit-ID import. Only the server key can call this.
create or replace function public.reset_import_sequences()
returns void language plpgsql security definer set search_path = '' as $$
begin
 perform setval(pg_get_serial_sequence('public.categories','id'),greatest(coalesce((select max(id) from public.categories),0),1),(select count(*)>0 from public.categories));
 perform setval(pg_get_serial_sequence('public.products','id'),greatest(coalesce((select max(id) from public.products),0),1),(select count(*)>0 from public.products));
 perform setval(pg_get_serial_sequence('public.enquiries','id'),greatest(coalesce((select max(id) from public.enquiries),0),1),(select count(*)>0 from public.enquiries));
end;
$$;
revoke all on function public.reset_import_sequences() from public,anon,authenticated;
grant execute on function public.reset_import_sequences() to service_role;
revoke all on function public.create_pending_profile() from public,anon,authenticated;
revoke all on function public.protect_last_administrator() from public,anon,authenticated;

-- Atomic import/seed into an empty catalogue. Explicit IDs preserve existing product links.
create or replace function public.import_catalogue(payload jsonb)
returns void language plpgsql security definer set search_path = '' as $$
begin
 lock table public.categories, public.products, public.enquiries in exclusive mode;
 if exists(select 1 from public.categories) or exists(select 1 from public.products) or exists(select 1 from public.enquiries) then
  raise exception 'Import requires empty categories, products and enquiries';
 end if;
 insert into public.categories(id,slug,name,description,display_order,published)
 select id,slug,name,coalesce(description,''),coalesce(display_order,0),coalesce(published,true)
 from jsonb_populate_recordset(null::public.categories,coalesce(payload->'categories','[]'::jsonb));
 insert into public.products(id,code,slug,name,category_id,description,specifications,price,price_unit,price_display,availability,image,published,created_at,updated_at)
 select id,code,slug,name,category_id,coalesce(description,''),coalesce(specifications,''),price,coalesce(price_unit,'piece'),coalesce(price_display,'contact'),coalesce(availability,'enquire'),image,coalesce(published,false),coalesce(created_at,now()),coalesce(updated_at,now())
 from jsonb_populate_recordset(null::public.products,coalesce(payload->'products','[]'::jsonb));
 insert into public.enquiries(id,created_at,type,product,name,contact,company,qty,message,status,notes,emailed)
 select id,coalesce(created_at,now()),type,product,name,contact,company,qty,message,coalesce(status,'New'),coalesce(notes,''),coalesce(emailed,false)
 from jsonb_populate_recordset(null::public.enquiries,coalesce(payload->'enquiries','[]'::jsonb));
 perform public.reset_import_sequences();
end;
$$;
revoke all on function public.import_catalogue(jsonb) from public,anon,authenticated;
grant execute on function public.import_catalogue(jsonb) to service_role;
