-- Run once in Supabase SQL Editor. No private table is readable using the public key.
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  slug text not null unique, name text not null,
  description text not null default '', display_order integer not null default 0,
  published boolean not null default true
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  code text not null unique, slug text not null unique, name text not null,
  category_id bigint references public.categories(id) on delete restrict,
  description text not null default '', specifications text not null default '',
  price double precision check(price >= 0), price_unit text not null default 'piece',
  price_display text not null default 'contact' check(price_display in ('public','contact','quote')),
  availability text not null default 'enquire' check(availability in ('available','unavailable','enquire')),
  image text, published boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  check(price_display <> 'public' or price is not null)
);
create index if not exists products_category_id_idx on public.products(category_id);
create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(), type text, product text, name text,
  contact text, company text, qty text, message text,
  status text not null default 'New' check(status in ('New','In Progress','Awaiting Customer','Responded','Closed')),
  notes text not null default '', emailed boolean not null default false
);
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  role text not null default 'pending' check(role in ('pending','staff','administrator')),
  created_at timestamptz not null default now()
);
-- Signup metadata cannot grant staff permissions. Only server-held credentials promote users.
create or replace function public.create_pending_profile()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id,username,role)
  values(new.id, 'user-' || new.id::text, 'pending');
  return new;
end;
$$;
drop trigger if exists create_tatatex_profile on auth.users;
create trigger create_tatatex_profile after insert on auth.users
for each row execute function public.create_pending_profile();

create or replace function public.protect_last_administrator()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.role = 'administrator' and (tg_op = 'DELETE' or new.role <> 'administrator') then
    perform pg_advisory_xact_lock(7848321);
    if (select count(*) from public.profiles where role='administrator') <= 1 then
      raise exception 'Keep at least one administrator';
    end if;
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
drop trigger if exists keep_tatatex_administrator on public.profiles;
create trigger keep_tatatex_administrator before delete or update of role on public.profiles
for each row execute function public.protect_last_administrator();

